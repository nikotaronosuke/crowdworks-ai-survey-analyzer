/** 区切り文字を人が読める形にする */
function delimiterName(delimiter: string): string {
  switch (delimiter) {
    case '\t':
      return 'タブ区切り (TSV)';
    case ',':
      return 'カンマ区切り (CSV)';
    case ';':
      return 'セミコロン区切り';
    case '|':
      return 'パイプ区切り';
    default:
      return `"${delimiter}" 区切り`;
  }
}

/**
 * データ読み込みセクションを作る。
 * @param ctx アプリ本体への窓口（読み込み結果の反映とエラー表示に使う）
 */
export function createLoadSection(ctx: AppContext): Section {
  // 読み込み結果（データ名・件数・警告）を出す領域。render で作り直す。
  const status = el('div');

  const fileInput = el('input', {
    type: 'file',
    class: 'file-input',
    accept: '.csv,.tsv,.txt,text/csv,text/tab-separated-values,text/plain',
  });

  const textarea = el('textarea', {
    rows: 8,
    placeholder:
      '表計算ソフトからコピーした内容や、CSV / TSV の中身をここに貼り付けてください。\n1行目は列名（設問文）にしてください。',
  });

  /** RawTable を Dataset にしてアプリへ反映する */
  function applyTable(table: RawTable, label: string): void {
    try {
      const dataset = buildDataset(table);
      const message =
        dataset.rows.length === 0
          ? `${label}：データ行が見つかりませんでした。1行目が列名、2行目以降が回答になっているか確認してください。`
          : `${label}（${fmtInt(dataset.rows.length)}件 / ${fmtInt(dataset.headers.length)}列）を読み込みました。`;
      ctx.loadDataset(dataset, message);
    } catch (error) {
      ctx.reportError('データの解釈に失敗しました', error);
    }
  }

  /** File を読み込む（UTF-8 / Shift_JIS の判定は parseFile に任せる） */
  async function handleFile(file: File): Promise<void> {
    try {
      const table = await parseFile(file);
      applyTable(table, file.name);
    } catch (error) {
      ctx.reportError('ファイルの読み込みに失敗しました', error);
    }
  }

  /** 貼り付けテキストを読み込む */
  function handlePastedText(): void {
    const text = textarea.value;
    if (text.trim() === '') {
      ctx.setMessage('テキストが空です。CSV / TSV の中身を貼り付けてください。');
      return;
    }
    try {
      applyTable(parseText(text, '貼り付けデータ'), '貼り付けデータ');
    } catch (error) {
      ctx.reportError('貼り付けたテキストの読み込みに失敗しました', error);
    }
  }

  /** 同梱のサンプルを読み込む（通信は行わない） */
  function handleSample(): void {
    try {
      applyTable(parseText(SAMPLE_CSV, 'サンプルデータ（架空・30件）'), 'サンプルデータ');
    } catch (error) {
      ctx.reportError('サンプルデータの読み込みに失敗しました', error);
    }
  }

  const dropzone = el(
    'div',
    {
      class: 'dropzone',
      on: {
        dragenter: (e: Event) => {
          e.preventDefault();
          dropzone.classList.add('dragover');
        },
        dragover: (e: Event) => {
          e.preventDefault();
          const dt = (e as DragEvent).dataTransfer;
          if (dt) dt.dropEffect = 'copy';
          dropzone.classList.add('dragover');
        },
        dragleave: () => dropzone.classList.remove('dragover'),
        drop: (e: Event) => {
          e.preventDefault();
          dropzone.classList.remove('dragover');
          const file = (e as DragEvent).dataTransfer?.files?.[0];
          if (file) {
            void handleFile(file);
          } else {
            ctx.setMessage('ドロップされたファイルを取得できませんでした。');
          }
        },
      },
    },
    [
      el('p', { class: 'dropzone-title' }, ['CSV / TSV ファイルをここにドロップ']),
      el('p', { class: 'note' }, [
        'UTF-8 と Shift_JIS のどちらでも読み込めます。ファイルはこの端末から出ません。',
      ]),
      el('div', { class: 'row' }, [
        el(
          'button',
          {
            class: 'btn primary',
            type: 'button',
            on: { click: () => fileInput.click() },
          },
          ['ファイルを選択'],
        ),
        el(
          'button',
          {
            class: 'btn',
            type: 'button',
            on: { click: handleSample },
          },
          ['サンプルデータを読み込む'],
        ),
      ]),
    ],
  );

  fileInput.addEventListener('change', () => {
    const file = fileInput.files?.[0];
    if (file) void handleFile(file);
    // 同じファイルを続けて選び直せるように値をリセットする
    fileInput.value = '';
  });

  const element = el('section', { class: 'card' }, [
    el('div', { class: 'card-head' }, [
      el('h2', undefined, ['1. データを読み込む']),
      el('span', { class: 'badge ok' }, ['この端末の中だけで処理']),
    ]),
    dropzone,
    fileInput,
    el('p', { class: 'note' }, ['または、CSV / TSV のテキストを直接貼り付けてください。']),
    textarea,
    el('div', { class: 'row' }, [
      el(
        'button',
        { class: 'btn', type: 'button', on: { click: handlePastedText } },
        ['テキストを読み込む'],
      ),
      el(
        'button',
        {
          class: 'btn ghost',
          type: 'button',
          on: {
            click: () => {
              textarea.value = '';
            },
          },
        },
        ['貼り付け欄をクリア'],
      ),
    ]),
    status,
    el('p', { class: 'note' }, [
      '読み込んだ回答はブラウザのメモリ上にだけ置かれます。保存はされないため、リロードすると消えます。',
    ]),
  ]);

  return {
    element,
    render(state: AppState): void {
      const ds = state.dataset;
      const children: Node[] = [];

      if (!ds) {
        children.push(el('p', { class: 'note' }, ['まだデータを読み込んでいません。']));
      } else {
        children.push(
          el('div', { class: 'row' }, [
            el('span', { class: 'badge ok' }, ['読み込み済み']),
            el('span', undefined, [ds.sourceName]),
            el('span', { class: 'badge' }, [`${fmtInt(ds.rows.length)}件`]),
            el('span', { class: 'badge' }, [`${fmtInt(ds.headers.length)}列`]),
            el('span', { class: 'badge' }, [delimiterName(ds.delimiter)]),
            ds.warnings.length > 0
              ? el('span', { class: 'badge warn' }, [`警告 ${fmtInt(ds.warnings.length)}件`])
              : el('span', { class: 'badge ok' }, ['警告なし']),
          ]),
        );

        if (ds.warnings.length > 0) {
          children.push(
            el(
              'ul',
              { class: 'warnings' },
              ds.warnings.map((w) => el('li', undefined, [w])),
            ),
          );
        }
      }

      status.replaceChildren(...children);
    },
  };
}
